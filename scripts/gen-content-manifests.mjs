import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PROJECTS, CHALLENGES } from '../src/content/index.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const CONTENT = path.resolve(__dirname, '../src/content')
const BANNER = '// Generated by scripts/gen-content-manifests.mjs. Do not edit.\n'

const LIST_FIELDS = [
  'id', 'title', 'description', 'difficulty', 'category',
  'topic', 'xp', 'order', 'language', 'project_id', 'project_title',
]

const pick = (obj, fields) => {
  const out = {}
  for (const f of fields) if (obj[f] !== undefined) out[f] = obj[f]
  return out
}

const write = (file, name, data) => {
  const next = `${BANNER}export const ${name} = ${JSON.stringify(data, null, 0)}\n`
  const target = path.join(CONTENT, file)
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current === next) {
    console.log(`[manifests] ${file} up to date (${data.length})`)
    return
  }
  fs.writeFileSync(target, next)
  console.log(`[manifests] wrote ${file}: ${data.length} entries, ${(next.length / 1024).toFixed(0)}K`)
}

write('projects.generated.js', 'PROJECTS', PROJECTS)
write('challenges.generated.js', 'CHALLENGE_SUMMARIES', CHALLENGES.map((c) => pick(c, LIST_FIELDS)))
