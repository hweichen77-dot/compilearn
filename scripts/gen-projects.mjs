import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PROJECTS } from '../src/content/index.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(__dirname, '../src/content/projects.generated.js')

const banner = '// Generated by scripts/gen-projects.mjs. Do not edit.\n'
const body = `export const PROJECTS = ${JSON.stringify(PROJECTS, null, 0)}\n`

const next = banner + body
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''

if (current === next) {
  console.log(`[gen-projects] up to date (${PROJECTS.length} projects)`)
} else {
  fs.writeFileSync(OUT, next)
  console.log(`[gen-projects] wrote ${PROJECTS.length} projects, ${(next.length / 1024).toFixed(0)}K`)
}
